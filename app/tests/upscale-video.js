// Focal functional checks only: no captures, benchmarks or global runners.
const fs = require("fs"), os = require("os"), path = require("path"), assert = require("assert");
const { execFileSync } = require("child_process");
const { serve, launch, openApp, until } = require("./common");
const { createHost } = require("./host");
const root = fs.mkdtempSync(path.join(os.tmpdir(), "halation-upscale-video-"));
const ffmpeg = process.env.HALATION_TEST_FFMPEG || "ffmpeg", ffprobe = process.env.HALATION_TEST_FFPROBE || "ffprobe";
const span = process.env.HALATION_TEST_SPAN;
assert(span, "Point HALATION_TEST_SPAN at the existing SPAN folder; no downloads are performed.");
const source = path.join(root, "odd-cfr.mp4");
execFileSync(ffmpeg, ["-v", "error", "-f", "lavfi", "-i", "testsrc=size=65x49:rate=24000/1001", "-f", "lavfi", "-i", "sine=frequency=440:sample_rate=48000:duration=0.25025", "-frames:v", "6", "-c:v", "libx264", "-pix_fmt", "yuv444p", "-c:a", "aac", source]);
const metadata = p => JSON.parse(execFileSync(ffprobe, ["-v", "error", "-show_streams", "-of", "json", p]));
const audioHash = p => execFileSync(ffmpeg, ["-v", "error", "-i", p, "-map", "0:a:0", "-c", "copy", "-f", "hash", "-hash", "sha256", "-"]).toString();
const host = createHost(root, { tools: { systemFfmpeg: ffmpeg, systemFfprobe: ffprobe, span: { bin: path.join(span, "span-ncnn-vulkan.exe"), models: path.join(span, "models") } } });
fs.writeFileSync(path.join(host.base, "Settings/app.json"), JSON.stringify({ settings: { language: "en" } }));
(async () => {
  const server = serve(), browser = await launch();
  try {
    const app = await openApp(browser, server, host);
    await app.tab("upscale"); await app.appReady("upscale");
    const frame = app.page.frames().find(f => /upscale\.html/.test(f.url()));
    await frame.evaluate(p => { window.testSource = p; return window.__halApp.takeVideo({ path: p, name: "odd-cfr.mp4" }); }, source);
    assert(await until(() => frame.locator("#videoRun").isEnabled(), 20000), "Video input and installed dependencies enable Upscale");
    assert.equal(await frame.locator("#videoPlan").textContent(), "130 × 98 · 24000/1001 FPS · 0:00");
    await frame.locator("#videoRun").click();
    assert(await until(() => frame.evaluate(() => !!window.__upscaleVideo.result()), 60000), await frame.locator("#videoStatus").textContent());
    const result = await frame.evaluate(() => window.__upscaleVideo.result());
    const streams = metadata(result.path).streams, v = streams.find(s => s.codec_type === "video");
    assert.equal(v.width, 130); assert.equal(v.height, 98); assert.equal(v.nb_frames, "6"); assert.equal(v.avg_frame_rate, "24000/1001"); assert.equal(v.codec_name, "h264");
    assert.equal(audioHash(source), audioHash(result.path), "Audio packets are preserved");
    assert(await frame.locator("#videoTransport").isVisible());
    await frame.locator("#videoPlay").click();
    assert(await until(async () => (await frame.locator("#videoSeek").inputValue()) !== "0", 10000), "Result plays with the shared viewer");
    await frame.locator("#imageTab").click();
    assert(await frame.locator("#imageView").isVisible()); assert(!await frame.locator("#videoView").isVisible());
    await frame.locator("#videoTab").click();
    await frame.locator('[data-video-scale="4"]').click();
    assert.equal(await frame.locator("#videoPlan").textContent(), "260 × 196 · 24000/1001 FPS · 0:00");
    await frame.locator("#videoRun").click();
    assert(await until(() => frame.evaluate(() => window.__upscaleVideo.result()?.info.w === 260), 60000), await frame.locator("#videoStatus").textContent());
    const result4 = await frame.evaluate(() => window.__upscaleVideo.result());
    const v4 = metadata(result4.path).streams.find(s => s.codec_type === "video");
    assert.equal(v4.width, 260); assert.equal(v4.height, 196); assert.equal(v4.avg_frame_rate, "24000/1001"); assert.equal(v4.nb_frames, "6");
    assert.equal(audioHash(source), audioHash(result4.path));
    await frame.locator('[data-video-scale="2"]').click();
    // Cancel the actual runner, including its process and workspace lease.
    const longer = path.join(root, "cancel.mp4");
    execFileSync(ffmpeg, ["-v", "error", "-f", "lavfi", "-i", "testsrc=size=65x49:rate=24", "-frames:v", "120", "-c:v", "libx264", "-pix_fmt", "yuv444p", longer]);
    await frame.evaluate(p => window.__halApp.takeVideo({ path: p, name: "cancel.mp4" }), longer);
    const before = fs.readdirSync(path.join(host.base, "Exports/Upscaled"));
    await frame.locator("#videoRun").click();
    assert(await until(() => frame.evaluate(() => window.__upscale.HAL.jobs.list().some(j => j.title === "cancel.mp4" && j.state === "running")), 10000));
    await frame.locator("#videoCancel").click();
    assert(await until(() => frame.evaluate(() => window.__upscale.HAL.jobs.list().some(j => j.title === "cancel.mp4" && j.state === "cancelled")), 10000));
    assert.deepEqual(fs.readdirSync(path.join(host.base, "Exports/Upscaled")), before);
    const hdr = path.join(root, "hdr.mp4");
    execFileSync(ffmpeg, ["-v", "error", "-i", source, "-c:v", "libx264", "-pix_fmt", "yuv444p", "-color_trc", "smpte2084", "-c:a", "copy", hdr]);
    await frame.evaluate(p => window.__halApp.takeVideo({ path: p, name: "hdr.mp4" }), hdr);
    assert.match(await frame.locator("#videoStatus").textContent(), /supports SDR/);
    const vfr = path.join(root, "vfr.mp4");
    execFileSync(ffmpeg, ["-v", "error", "-i", source, "-vf", "setpts=PTS+floor(N/3)*0.05/TB", "-fps_mode", "vfr", "-c:v", "libx264", "-pix_fmt", "yuv444p", "-an", vfr]);
    await frame.evaluate(p => window.__halApp.takeVideo({ path: p, name: "vfr.mp4" }), vfr);
    await frame.locator("#videoRun").click();
    assert(await until(async () => /supports SDR/.test(await frame.locator("#videoStatus").textContent()), 15000), "VFR rejected before SPAN");
    assert.deepEqual(fs.readdirSync(path.join(host.base, "Exports/Upscaled")), before);
    assert.equal(app.errors.filter(e => /pageerror:/.test(e)).length, 0, app.errors.join("\n"));
    await app.tab("settings");
    assert(await until(() => app.page.locator('#tools [data-key="span"]').isVisible(), 10000));
    assert.match(await app.page.locator('#tools [data-key="span"]').textContent(), /Video Upscale \/ SPAN/);
    assert.equal((await host.call("storage_report", {})).components.filter(c => c.id === "span").length, 1);
    console.log("PASS: real SPAN ×2/×4, odd dimensions, six frames, exact 24000/1001 FPS, audio copy, playback, mode preservation, SDR/CFR guards, cancellation and existing Settings component row. No captures or installations.");
  } finally { await browser.close(); server.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
