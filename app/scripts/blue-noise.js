// Generates Auralis' stationary micrograin: a 128×128 blue-noise threshold map by void-and-cluster (Ulichney, 1993),
// written as base64 bytes to app/dist/blue-noise.js (window.__auralisBlueNoise). Deterministic: same seed, same bytes.
// Usage: node app/scripts/blue-noise.js [--check]   (--check only verifies that the committed file is up to date)
const fs = require("fs");
const path = require("path");

const SIZE = 128, N = SIZE * SIZE, SIGMA = 1.5, RADIUS = 7, SEED = 0x48616c61;
const OUT = path.join(__dirname, "..", "dist", "blue-noise.js");

/* ===== energy ===== */
// Toroidal Gaussian kernel; a pixel's energy is the sum of the kernel over the set pixels around it.
const kernel = [];
for (let dy = -RADIUS; dy <= RADIUS; dy++) for (let dx = -RADIUS; dx <= RADIUS; dx++)
  kernel.push([dx, dy, Math.exp(-(dx * dx + dy * dy) / (2 * SIGMA * SIGMA))]);
function splat(energy, i, sign) {
  const x = i % SIZE, y = (i / SIZE) | 0;
  for (const [dx, dy, w] of kernel) energy[((y + dy + SIZE) % SIZE) * SIZE + (x + dx + SIZE) % SIZE] += sign * w;
}
// The tightest cluster: the set pixel with most energy; the largest void: the empty pixel with least.
function extreme(bits, energy, want, max) {
  let best = -1, value = max ? -Infinity : Infinity;
  for (let i = 0; i < N; i++) if (bits[i] === want && (max ? energy[i] > value : energy[i] < value)) { value = energy[i]; best = i; }
  return best;
}

/* ===== void and cluster ===== */
function generate() {
  let s = SEED;
  const random = () => { s = s + 0x6d2b79f5 | 0; let t = Math.imul(s ^ s >>> 15, 1 | s); t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t; return ((t ^ t >>> 14) >>> 0) / 4294967296; };
  // initial pattern: a tenth of the pixels at random, then relaxed until the tightest cluster is the largest void
  const initial = new Uint8Array(N), energy = new Float64Array(N);
  let ones = 0;
  while (ones < N / 10) { const i = (random() * N) | 0; if (!initial[i]) { initial[i] = 1; splat(energy, i, 1); ones++; } }
  for (;;) {
    const cluster = extreme(initial, energy, 1, true);
    initial[cluster] = 0; splat(energy, cluster, -1);
    const hole = extreme(initial, energy, 0, false);
    if (hole === cluster) { initial[cluster] = 1; splat(energy, cluster, 1); break; }
    initial[hole] = 1; splat(energy, hole, 1);
  }
  const rank = new Int32Array(N);
  // phase 1: remove the tightest clusters of the initial pattern, highest rank first
  const bits = initial.slice(), e1 = energy.slice();
  for (let r = ones - 1; r >= 0; r--) { const i = extreme(bits, e1, 1, true); bits[i] = 0; splat(e1, i, -1); rank[i] = r; }
  // phases 2 and 3: fill the largest voids up to every pixel (with a full kernel the tightest cluster of the empty
  // pixels is the largest void of the set ones, so one rule covers both halves)
  bits.set(initial); const e2 = energy;
  for (let r = ones; r < N; r++) { const i = extreme(bits, e2, 0, false); bits[i] = 1; splat(e2, i, 1); rank[i] = r; }
  return Uint8Array.from(rank, r => Math.floor(r * 256 / N));
}

/* ===== output ===== */
const bytes = generate();
const text = "// Generated by app/scripts/blue-noise.js (void-and-cluster, 128×128, 8-bit ranks); do not edit.\n" +
  "window.__auralisBlueNoise = \"" + Buffer.from(bytes).toString("base64") + "\";\n";
if (process.argv.includes("--check")) {
  if (!fs.existsSync(OUT) || fs.readFileSync(OUT, "utf8") !== text) { console.error("app/dist/blue-noise.js is out of date"); process.exit(1); }
  console.log("blue-noise.js is up to date");
} else { fs.writeFileSync(OUT, text); console.log("wrote", path.relative(process.cwd(), OUT), bytes.length, "bytes"); }
